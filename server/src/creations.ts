/** The creations of `kind` among `ids` (the rewards editor): known, and whether archived. */
export async function knownCreations(ctx: Ctx, kind: CreationKind, ids: number[]): Promise<Map<number, { archived: boolean }>> {
    const out = new Map<number, { archived: boolean }>();
    if (ids.length === 0) return out;
    const rows = await ctx.env.DB.prepare("SELECT id, archived FROM creations WHERE kind = ?1 AND id IN (SELECT value FROM json_each(?2))")
        .bind(kind, JSON.stringify(ids))
        .all<{ id: number; archived: number }>();
    for (const r of rows.results) out.set(r.id, { archived: r.archived === 1 });
    return out;
}

/** The suits created on the server among `ids` (kept for the callers of 2.45). */
export const knownSuits = (ctx: Ctx, ids: number[]) => knownCreations(ctx, "suit", ids);
