// ADMINISTRATION › Créations: things an administrator makes on the server that every game
// draws without an update. Four kinds, each a category of the Collection:
//   - the suits (« Combinaisons »): a name and three colours (the suit, its accent, its scarf),
//     which the game applies to Nova's sheet the way tools/assetgen/characters/nova_suits.py
//     makes the catalogue's suits (game/cosmetics/SuitRecolor.cpp);
//   - (2.59) the trails (« Traînées »): two colours (start, end), a style among those the game
//     draws (TRAIL_STYLES), a width, how long the trace lasts and its sparkles;
//   - (2.59) the avatar frames (« Cadres »): two colours (border, glow) and a style (FRAME_STYLES);
//   - (2.59) the victory effects (« Effets de victoire »): two colours (main, second) and a style
//     (VICTORY_STYLES). The game draws them in ui/screens/CosmeticFx.cpp; the lists here are the
//     same as its own (game/cosmetics/CreationLooks.cpp): a style it does not know is refused.
// A creation is given as the reward of a challenge (challengeRewards.ts: reward_kind its kind,
// ref "srv<kind>:<id>") and worn only once won (cosmetics.ts).
//
// The administrator comes from the session only (requireAdminRole: any other account gets the
// 404 of an unknown route); every change and every refusal is written to the Journal. A
// creation is never deleted, only archived: it is no longer offered as a new reward, and the
// players who won it keep it (the public list still gives its look while anyone has it, or
// a challenge gives it). Nothing here touches a run, a replay or a record.
//
// 2.60 « Réserve du jeu »: the game brings its own creations too (migration 0118, generated by
// scripts/creations-reserve.mjs: `game_reserve` = 1, `created_by` NULL), real ones an
// administrator gives, renames or archives like the others. No player sees a creation before a
// challenge that has begun gives it, or a player won it (GET /creations): the reserve, and a
// creation only planned as the reward of a coming challenge, stay in the administration.

