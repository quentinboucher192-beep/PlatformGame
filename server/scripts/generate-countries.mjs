// Generates migrations/0002_countries.sql from the game's country list
// (data/online/country_codes.json, built by tools/globegen). Run once when the country
// list changes, as a NEW migration file (applied migrations are never edited).
//   node scripts/generate-countries.mjs [output.sql]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../data/online/country_codes.json");
const out = resolve(here, "..", process.argv[2] ?? "migrations/0002_countries.sql");
const { codes } = JSON.parse(readFileSync(source, "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const num = (n) => (typeof n === "number" && Number.isFinite(n) ? String(n) : "NULL");
const lines = [
    "-- Countries and their approximate representation point (centre of the largest landmass).",
    "-- Generated by scripts/generate-countries.mjs from data/online/country_codes.json",
    "-- (Natural Earth / i18n-iso-countries / GeoNames, see licenses/). Never a personal position.",
];
for (const c of codes) {
    if (!/^[A-Z]{2}$/.test(c.code)) throw new Error(`code invalide: ${c.code}`);
    lines.push(`INSERT INTO countries (code, name_fr, name_en, latitude, longitude) VALUES (${q(c.code)}, ${q(c.name_fr)}, ${q(c.name_en)}, ${num(c.lat)}, ${num(c.lon)});`);
}
writeFileSync(out, lines.join("\n") + "\n");
console.log(`${codes.length} pays -> ${out}`);
