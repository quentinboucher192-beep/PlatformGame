// Registers a game installer offered to players (in-game "nouvelle version" notification):
//   node scripts/release-migration.mjs 2.4.0 path/to/CosmicPlatformer-Setup-2.4.0.exe "notes" | --changelog \
//       > migrations/0NNN_release_2_4_0.sql      (a number above 0170: the column notes_en)
// then upload the file to the environment's bucket under the same key, and apply:
//   npx wrangler r2 object put cosmic-online-staging-files/releases/CosmicPlatformer-Setup-2.4.0.exe \
//       --file path/to/CosmicPlatformer-Setup-2.4.0.exe --remote --env staging
//   npx wrangler d1 migrations apply cosmic-online-staging --remote --env staging
// 2.76.2: the notes are written in French and in English (notes_en), each line translated by the
// game's dictionary (data/i18n/en.json; tools/i18n/extract.py --check asks for every line). A 4th
// argument gives the English notes by hand. The English notes of the installers published before
// (migration 0170): node scripts/release-migration.mjs --english-backfill.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { englishNotes, releasesOfMigrations, sqlText } from "./release-notes.mjs";

const here = path.dirname(new URL(import.meta.url).pathname);
const dictionary = () => JSON.parse(fs.readFileSync(path.join(here, "../../data/i18n/en.json"), "utf8")).strings ?? {};

// --english-backfill: the English notes of every installer registered by the migrations so far.
if (process.argv[2] === "--english-backfill") {
    const dir = path.join(here, "../migrations");
    const files = Object.fromEntries(
        fs
            .readdirSync(dir)
            .sort()
            .map((f) => [f, fs.readFileSync(path.join(dir, f), "utf8")]),
    );
    const strings = dictionary();
    let missing = 0;
    for (const r of releasesOfMigrations(files)) {
        const en = englishNotes(r.notes, strings);
        if (en === null) {
            missing++;
            console.error(`notes de ${r.version} : une ligne sans traduction (python3 tools/i18n/extract.py)`);
            continue;
        }
        console.log(`UPDATE client_releases SET notes_en = ${sqlText(en)} WHERE version = ${sqlText(r.version)};`);
    }
    process.exit(missing ? 1 : 0);
}

const [version, file, notesArg = "", notesEnArg] = process.argv.slice(2);
// 2.62: "--changelog" = the notes of every version since the previous installer published
// (the last migrations/*_release_*.sql), read from data/news/changelog.json: a version that
// never had its own installer (2.61.0 → 2.61.1) is never left out of the notification.
function changelogNotes(v) {
    const log = JSON.parse(fs.readFileSync(path.join(here, "../../data/news/changelog.json"), "utf8"));
    const k = (s) => s.split(".").map(Number).reduce((acc, n) => acc * 1000 + n, 0);
    const prev = fs
        .readdirSync(path.join(here, "../migrations"))
        .map((f) => /_release_(\d+)_(\d+)_(\d+)\.sql$/.exec(f))
        .filter(Boolean)
        .map((m) => `${m[1]}.${m[2]}.${m[3]}`)
        .filter((x) => k(x) < k(v))
        .sort((x, y) => k(y) - k(x))[0];
    const out = [];
    for (const ver of Object.keys(log).sort((x, y) => k(y) - k(x))) {
        if (k(ver) > k(v) || (prev && k(ver) <= k(prev))) continue;
        out.push(`Version ${ver} :\n` + log[ver].map((l) => "• " + l).join("\n"));
    }
    return out.join("\n\n");
}
const notes = notesArg === "--changelog" ? changelogNotes(version) : notesArg;
if (!/^\d{1,3}\.\d{1,3}\.\d{1,4}$/.test(version ?? "")) throw new Error("version invalide (x.y.z)");
const data = fs.readFileSync(file);
if (data.length < 1024 || data[0] !== 0x4d || data[1] !== 0x5a) throw new Error("ce n'est pas un exécutable Windows");
const sha = crypto.createHash("sha256").update(data).digest("hex");
const [a, b, c] = version.split(".").map(Number);
const key = a * 1000000 + b * 1000 + c;
const name = `CosmicPlatformer-Setup-${version}.exe`;
const q = sqlText;
const notesEn = notesEnArg ?? englishNotes(notes, dictionary());
if (notesEn === null) throw new Error("notes sans traduction anglaise : python3 tools/i18n/extract.py (ou 4e argument)");
console.log(`-- Installer ${version} (${path.basename(file)}, ${data.length} bytes), generated by scripts/release-migration.mjs.`);
console.log(
    `INSERT INTO client_releases (version, version_key, platform, file_key, file_name, size, sha256, notes, notes_en, published_at) VALUES (${q(version)}, ${key}, 'windows', ${q("releases/" + name)}, ${q(name)}, ${data.length}, ${q(sha)}, ${q(notes)}, ${q(notesEn)}, ${q(new Date().toISOString())}) ON CONFLICT (version) DO NOTHING;`,
);
