// Turns the output of `CosmicPlatformer --online-manifest manifest.json` into a D1 migration
// that registers the levels of a game release exactly like POST /admin/levels does (new
// revisions become current, older ones legacy; an existing revision is never modified), so
// that a release can be registered with `wrangler d1 migrations apply` without any
// administration secret.
//   node scripts/levels-migration.mjs manifest.json > migrations/000N_levels_<version>.sql
import fs from "node:fs";

const manifest = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
if (manifest.format !== "cosmic.online_manifest" || !Array.isArray(manifest.levels)) throw new Error("manifeste invalide");
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const n = (x) => {
    if (typeof x !== "number" || !Number.isFinite(x)) throw new Error("nombre invalide");
    return String(x);
};
const hash = (h) => {
    if (!/^[0-9a-f]{64}$/.test(h)) throw new Error("empreinte invalide");
    return q(h);
};
const id = (s) => {
    if (!/^[a-z0-9_]{1,64}$/.test(s)) throw new Error("identifiant invalide : " + s);
    return q(s);
};
const game = manifest.game_version;
if (!/^\d{1,3}\.\d{1,3}\.\d{1,4}$/.test(game)) throw new Error("version du jeu invalide");
const now = new Date().toISOString();
const out = [
    `-- Levels of Cosmic Platformer ${game} (generated by scripts/levels-migration.mjs from`,
    `-- CosmicPlatformer --online-manifest). Same effect as POST /admin/levels.`,
    "",
];
for (const l of manifest.levels) {
    out.push(`-- ${l.id} révision ${l.version}`);
    out.push(
        `INSERT INTO levels (id, name, planet_id, planet_name, level_order, current_version, content_hash, ranking_enabled) VALUES (${id(l.id)}, ${q(l.name)}, ${id(l.planet_id)}, ${q(l.planet_name ?? "")}, ${n(l.order)}, ${n(l.version)}, ${hash(l.content_hash)}, 1) ON CONFLICT (id) DO UPDATE SET name = excluded.name, planet_id = excluded.planet_id, planet_name = excluded.planet_name, level_order = excluded.level_order;`,
    );
    out.push(
        `INSERT INTO level_versions (level_id, version, content_hash, compatibility_status, min_game_version, total_collectibles, total_enemies, time_limit_ms, min_time_ms, bounds_w, bounds_h, spawn_x, spawn_y, exit_x, exit_y, exit_w, exit_h, created_at) VALUES (${id(l.id)}, ${n(l.version)}, ${hash(l.content_hash)}, 'active', ${q(game)}, ${n(l.total_collectibles)}, ${n(l.total_enemies)}, ${n(l.time_limit_ms)}, ${n(l.min_time_ms)}, ${n(l.bounds[0])}, ${n(l.bounds[1])}, ${n(l.spawn[0])}, ${n(l.spawn[1])}, ${n(l.exit[0])}, ${n(l.exit[1])}, ${n(l.exit[2])}, ${n(l.exit[3])}, ${q(now)}) ON CONFLICT (level_id, version) DO NOTHING;`,
    );
    out.push(`UPDATE levels SET current_version = ${n(l.version)}, content_hash = ${hash(l.content_hash)} WHERE id = ${id(l.id)} AND current_version <= ${n(l.version)};`);
    out.push(
        `UPDATE level_versions SET compatibility_status = 'legacy' WHERE level_id = ${id(l.id)} AND version < ${n(l.version)} AND compatibility_status = 'active';`,
    );
    out.push("");
}
process.stdout.write(out.join("\n"));
