#!/usr/bin/env python3
"""Version d'apparition de chaque asset : écrit data/assets/asset_versions.json.

ADMINISTRATION › Assets (2.69) montre la pastille « NOUVEAU » sur chaque asset arrivé dans une
version plus récente que celle que le joueur avait (game/progression/NewBadges.h : la même règle
que pour data/news/new_features.json, sans une ligne par asset). Ce fichier donne, pour chaque
fichier de assets/, la version du jeu où il est apparu :
  · amorcé une seule fois depuis l'historique git (--seed) : pour chaque fichier, les commits qui
    l'ont ajouté (sans suivre les renommages) → la plus ancienne de leurs versions ;
  · ensuite, chaque lancement garde les versions déjà connues, donne aux fichiers apparus depuis
    la version en préparation et retire ceux qui ne sont plus installés. Rien d'autre ne change :
    le résultat ne dépend que de assets/, de ce fichier et de la version en préparation.
La version d'un commit (ou celle en préparation) est la plus récente de VERSION dans
CMakeLists.txt et des entrées de data/news/changelog.json : une nouveauté entre au journal avant
que CMakeLists.txt ne passe à sa version, à la livraison.

Les assets plus anciens que PILLS_FROM ne portent jamais la pastille (« pillsFrom ») : les
pastilles des assets arrivent en 2.69 et ce qui précède les raids (2.65.0) n'est plus nouveau,
quelle que soit la version que le joueur avait.

Après une fusion (merge) qui apporte des assets, relancer ce script (code_refs.py le relance
aussi, et le test « asset versions: every installed asset has its version » de
tests/test_new_badges.cpp échoue tant qu'il n'est pas à jour). Un fichier resté en conflit
(marqueurs <<<<<<< ======= >>>>>>>) est relu ligne à ligne : les deux côtés sont gardés, la plus
ancienne version l'emporte.

Usage (depuis la racine du dépôt) :
    python3 tools/assets/asset_versions.py              # met à jour data/assets/asset_versions.json
    python3 tools/assets/asset_versions.py --check      # code de sortie 1 s'il n'est pas à jour
    python3 tools/assets/asset_versions.py --seed       # recalcule tout depuis l'historique git
    python3 tools/assets/asset_versions.py --self-test  # vérifie le générateur lui-même
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REL_OUT = "data/assets/asset_versions.json"
PILLS_FROM = "2.65.0"
VERSION_RE = re.compile(r"^\d{1,3}\.\d{1,3}\.\d{1,4}$")
COMMENT = ("Version of the game in which each file of assets/ first appeared (generated by tools/assets/asset_versions.py: do not "
           "edit). An asset newer than the version the player had carries the « NOUVEAU » pill in ADMINISTRATION › Assets "
           "(game/progression/NewBadges.h); none older than « pillsFrom » ever does.")
# Lines of a JSON object « "key": "1.2.3", » (the tolerant reading of a file left in conflict).
LINE_RE = re.compile(r'^\s*"((?:[^"\\]|\\.)+)"\s*:\s*"(\d{1,3}\.\d{1,3}\.\d{1,4})"\s*,?\s*$')
TOP_KEYS = {"format", "comment", "pillsFrom", "versions"}


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def newest(*versions):
    vs = [v for v in versions if v and VERSION_RE.match(v)]
    return max(vs, key=vkey) if vs else None


def installed_assets(root):
    out = set()
    base = os.path.join(root, "assets")
    for d, _dirs, files in os.walk(base):
        for f in files:
            out.add(os.path.relpath(os.path.join(d, f), base).replace(os.sep, "/"))
    return out


def cmake_version(text):
    m = re.search(r"\bproject\s*\([^)]*?\bVERSION\s+(\d+\.\d+\.\d+)", text or "", re.S)
    return m.group(1) if m else None


def changelog_version(text):
    """The newest version of data/news/changelog.json (the one being prepared)."""
    if not text:
        return None
    try:
        doc = json.loads(text)
        return newest(*doc.keys()) if isinstance(doc, dict) else None
    except ValueError:
        return newest(*re.findall(r'^\s{0,4}"(\d+\.\d+\.\d+)"\s*:', text, re.M))


def release_version(cmake_text, changelog_text):
    return newest(cmake_version(cmake_text), changelog_version(changelog_text))


def read_file(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return None


def current_version(root):
    v = release_version(read_file(os.path.join(root, "CMakeLists.txt")), read_file(os.path.join(root, "data", "news", "changelog.json")))
    if not v:
        raise SystemExit("Version introuvable (CMakeLists.txt, data/news/changelog.json).")
    return v


def read_versions(text):
    """Asset → version of a file written by this script; a file left in conflict by a merge is
    read line by line (both sides kept, the oldest version wins)."""
    if not text:
        return {}
    try:
        doc = json.loads(text)
        versions = doc.get("versions", {}) if isinstance(doc, dict) else {}
        return {k: v for k, v in versions.items() if isinstance(k, str) and isinstance(v, str) and VERSION_RE.match(v)}
    except ValueError:
        out = {}
        for line in text.splitlines():
            m = LINE_RE.match(line)
            if not m or m.group(1) in TOP_KEYS:
                continue
            key = json.loads('"' + m.group(1) + '"')
            out[key] = m.group(2) if key not in out else min(out[key], m.group(2), key=vkey)
        return out


def update(known, assets, version):
    """Known versions kept, the new assets at `version`, those no longer installed dropped."""
    return {a: known.get(a, version) for a in assets}


def render(versions):
    doc = {
        "format": "cosmic.asset_versions",
        "comment": COMMENT,
        "pillsFrom": PILLS_FROM,
        "versions": {k: versions[k] for k in sorted(versions)},
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def git(root, *args):
    r = subprocess.run(["git", "-C", root] + list(args), capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip() or "git " + " ".join(args))
    return r.stdout


def batch(root, args, inputs, contents=False):
    """git cat-file --batch(-check) on `inputs`: one answer each (None: missing)."""
    if not inputs:
        return []
    r = subprocess.run(["git", "-C", root, "cat-file"] + args, input=("\n".join(inputs) + "\n").encode("utf-8"), capture_output=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.decode("utf-8", "replace").strip() or "git cat-file")
    out = r.stdout
    if not contents:
        return out.decode("utf-8", "replace").splitlines()
    res, i = [], 0
    for _ in inputs:
        nl = out.index(b"\n", i)
        head = out[i:nl].decode("utf-8", "replace").split()
        if len(head) < 3:  # « <name> missing »
            res.append(None)
            i = nl + 1
            continue
        size = int(head[2])
        res.append(out[nl + 1:nl + 1 + size].decode("utf-8", "replace"))
        i = nl + 1 + size + 1
    return res


def seed_versions(root, assets):
    """From git: each asset → the version that shipped the commit adding it, i.e. the oldest
    « Version X » commit (VERSION changed in CMakeLists.txt) having it in its history: an agent's
    commit keeps the previous VERSION and only enters the game with the next one. Added several
    times: the oldest. Renames are not followed (a moved file is a new asset). A file added after
    the last « Version X » commit, or unknown to git: the version in preparation."""
    log = git(root, "log", "--no-renames", "--diff-filter=A", "--name-only", "--format=@@%H", "--", "assets")
    added = {}
    commit = None
    for line in log.splitlines():
        if line.startswith("@@"):
            commit = line[2:].strip()
        elif line.startswith("assets/") and commit:
            added.setdefault(line[len("assets/"):], set()).add(commit)
    # Every commit's VERSION (CMakeLists.txt read once per distinct content), its parents.
    parents = {}
    for line in git(root, "rev-list", "--parents", "HEAD").splitlines():
        ids = line.split()
        if ids:
            parents[ids[0]] = ids[1:]
    order = sorted(parents)
    blobs = dict(zip(order, batch(root, ["--batch-check=%(objectname)"], [c + ":CMakeLists.txt" for c in order])))
    distinct = sorted({b for b in blobs.values() if " missing" not in b})
    texts = dict(zip(distinct, batch(root, ["--batch"], distinct, contents=True)))
    version = {c: cmake_version(texts.get(blobs[c])) for c in order}
    # A « Version X » commit: its VERSION is none of its parents' (a merge that bumps it too).
    bumps = [c for c in order if version[c] and all(version.get(p) != version[c] for p in parents[c])]
    bumps.sort(key=lambda c: (vkey(version[c]), c))
    # What each one shipped: its history not shipped by an older version (walked once).
    shipped = {}
    for b in bumps:
        stack = [b]
        while stack:
            c = stack.pop()
            if c in shipped:
                continue  # and so is its whole history, by an older or equal version
            shipped[c] = version[b]
            stack.extend(parents.get(c, ()))
    now = current_version(root)
    out = {}
    for a in assets:
        vs = [shipped.get(c, now) for c in added.get(a, ())]
        out[a] = min(vs, key=vkey, default=now)
    return out


def compute(root, seed=False):
    assets = installed_assets(root)
    if seed:
        return render(seed_versions(root, assets))
    old = read_file(os.path.join(root, REL_OUT))
    if old is None:  # first run: from the history
        return render(seed_versions(root, assets))
    return render(update(read_versions(old), assets, current_version(root)))


def run(root=ROOT, check=False, seed=False, quiet=False):
    """Writes (or checks) data/assets/asset_versions.json; 0 when it is up to date."""
    out = os.path.join(root, REL_OUT)
    old = read_file(out)
    if check and old is None:
        if not quiet:
            print(REL_OUT + " manque : lancez python3 tools/assets/asset_versions.py")
        return 1
    text = compute(root, seed and not check)
    if check:
        if old != text:
            if not quiet:
                print(REL_OUT + " n'est pas à jour : lancez python3 tools/assets/asset_versions.py")
            return 1
        if not quiet:
            print(REL_OUT + " est à jour.")
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    if not quiet:
        versions = json.loads(text)["versions"]
        fresh = sum(1 for v in versions.values() if vkey(v) >= vkey(PILLS_FROM))
        print("%s : %d assets, %d depuis %s (pastille « NOUVEAU » possible)." % (REL_OUT, len(versions), fresh, PILLS_FROM))
    return 0


def self_test():
    """The generator's own rules, on a small tree in a temporary folder."""
    failures = []

    def expect(cond, what):
        if not cond:
            failures.append(what)

    expect(release_version("project(X\n    VERSION 2.68.1\n)", '{"2.69.0": []}') == "2.69.0", "version en préparation (journal)")
    expect(release_version("project(X VERSION 2.70.0)", '{"2.69.0": []}') == "2.70.0", "version en préparation (CMake)")
    expect(release_version("project(X VERSION 2.70.0)", None) == "2.70.0", "sans journal")
    a = {"b/x.png": "2.10.0", "a/y.wav": "2.66.1", "fonts/Z.ttf": "1.0.0"}
    expect(render(a) == render(dict(reversed(list(a.items())))), "ordre d'écriture stable")
    expect(read_versions(render(a)) == a, "relecture")
    u = update(a, {"b/x.png", "c/new.png"}, "2.69.0")
    expect(u == {"b/x.png": "2.10.0", "c/new.png": "2.69.0"}, "ajout et retrait")
    conflict = ('{\n "versions": {\n  "a/old.png": "1.0.0",\n<<<<<<< HEAD\n  "g/one.png": "2.69.0",\n  "g/both.png": "2.70.0",\n'
                '=======\n  "g/two.png": "2.69.0",\n  "g/both.png": "2.69.0"\n>>>>>>> autre\n }\n}\n')
    expect(read_versions(conflict) == {"a/old.png": "1.0.0", "g/one.png": "2.69.0", "g/two.png": "2.69.0", "g/both.png": "2.69.0"},
           "fichier en conflit relu (les deux côtés)")
    with tempfile.TemporaryDirectory() as tmp:
        for p in ("assets/sprites/a.png", "assets/sounds/b.wav", "data/news/changelog.json", REL_OUT, "CMakeLists.txt"):
            os.makedirs(os.path.dirname(os.path.join(tmp, p)), exist_ok=True)
        with open(os.path.join(tmp, "CMakeLists.txt"), "w", encoding="utf-8") as fh:
            fh.write("project(T\n    VERSION 2.68.1)\n")
        with open(os.path.join(tmp, "data", "news", "changelog.json"), "w", encoding="utf-8") as fh:
            fh.write('{"2.69.0": ["x"], "2.68.1": ["y"]}')
        for p in ("assets/sprites/a.png", "assets/sounds/b.wav"):
            open(os.path.join(tmp, p), "wb").close()
        with open(os.path.join(tmp, REL_OUT), "w", encoding="utf-8") as fh:
            fh.write(render({"sprites/a.png": "2.40.0", "gone.png": "2.50.0"}))
        expect(run(tmp, check=True, quiet=True) == 1, "--check voit un fichier en retard")
        expect(run(tmp, quiet=True) == 0, "écriture")
        first = read_file(os.path.join(tmp, REL_OUT))
        expect(read_versions(first) == {"sprites/a.png": "2.40.0", "sounds/b.wav": "2.69.0"}, "nouvel asset à la version en préparation")
        expect(run(tmp, quiet=True) == 0 and read_file(os.path.join(tmp, REL_OUT)) == first, "deux lancements, même fichier")
        expect(run(tmp, check=True, quiet=True) == 0, "--check à jour")
    # On the game itself: the same text twice.
    if read_file(os.path.join(ROOT, REL_OUT)) is not None:
        expect(compute(ROOT) == compute(ROOT), "déterministe sur le jeu")
    for f in failures:
        print("ÉCHEC : " + f)
    if not failures:
        print("asset_versions.py : auto-test réussi.")
    return 1 if failures else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="vérifie sans écrire")
    ap.add_argument("--seed", action="store_true", help="recalcule toutes les versions depuis l'historique git")
    ap.add_argument("--self-test", action="store_true", help="vérifie les règles du générateur")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    return run(check=args.check, seed=args.seed)


if __name__ == "__main__":
    sys.exit(main())
